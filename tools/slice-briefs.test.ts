import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  BRIEF_MAX_LINES,
  findPart,
  findSection,
  matchesHeading,
  parseNumbers,
  sliceBrief,
} from "./slice-briefs.ts";

const cards = [
  "# Cards",
  "",
  "## 1. Model contract",
  "",
  "**Steps**",
  "",
  "1. Add the table.",
  "2. Add the writer.",
  "   It is idempotent.",
  "3. Add the reader.",
  "",
  "**Honesty:** say what is missing.",
  "Never zero.",
  "",
  "**Build notes** none.",
  "",
  "- **L1 · list** the list item",
  "  indented more",
  "- **L2 · other** another",
  "",
  "| id | what |",
  "|---|---|",
  "| T1 | first |",
  "| T2 | second |",
  "",
  "```",
  "## 1. Not a heading",
  "```",
  "",
  "## 1.1 Migrations",
  "",
  "Migrate.",
  "",
  "## 2. Twice",
  "## 2. Twice again",
].join("\n");
const read = (file: string) => {
  if (file === "cards.md") return cards;
  throw new Error(`no ${file}`);
};

describe("matchesHeading", () => {
  it("matches the text or a prefix at a boundary", () => {
    assert.equal(matchesHeading("1. Model contract", "1"), true);
    assert.equal(matchesHeading("1.1 Migrations", "1"), false);
    assert.equal(matchesHeading("Model contract", "model contract"), true);
  });
});

describe("findSection", () => {
  const lines = cards.split("\n");
  it("ignores fenced headings and runs to the next heading of its level", () => {
    const s = findSection(lines, "1", "cards.md");
    assert.equal(lines[s.start], "## 1. Model contract");
    assert.equal(lines[s.end], "## 1.1 Migrations");
  });
  it("refuses none or several matches", () => {
    assert.throws(
      () => findSection(lines, "9", "cards.md"),
      /no heading matches/,
    );
    assert.throws(
      () => findSection(lines, "2. Twice", "cards.md"),
      /matches 2 headings/,
    );
  });
});

describe("findPart", () => {
  const lines = cards.split("\n");
  const section = findSection(lines, "1", "cards.md");
  const text = (part: string) =>
    findPart(lines, section, part, "cards.md")
      .map((s) => lines.slice(s.start, s.end).join("\n"))
      .join("\n--\n");
  it("finds steps, labels, bold items and table rows", () => {
    assert.equal(
      text("Steps 2-3"),
      "2. Add the writer.\n   It is idempotent.\n--\n3. Add the reader.",
    );
    assert.equal(
      text("Honesty"),
      "**Honesty:** say what is missing.\nNever zero.",
    );
    assert.equal(text("L1"), "- **L1 · list** the list item\n  indented more");
    assert.equal(text("T2"), "| id | what |\n|---|---|\n--\n| T2 | second |");
  });
  it("refuses a part that matches nothing", () => {
    assert.throws(
      () => text("Nope"),
      /no steps, label, bold item or table row matches/,
    );
    assert.throws(() => text("Steps 9"), /no step 9/);
  });
  it("parses step numbers", () => {
    assert.deepEqual(parseNumbers("1, 3 and 5-6"), [1, 3, 5, 6]);
    assert.throws(() => parseNumbers("x"), /not a list/);
  });
});

describe("sliceBrief", () => {
  it("copies slices and writes tests, owns and map into the check", () => {
    const source = [
      "# Brief",
      "@include cards.md § 1 › Steps 1; Honesty",
      "@tests packages/db/src/a.test.ts",
      "@owns packages/db/src/ tools/",
      "@owns tools/",
      "@map packages/db/src/a.ts",
      "end",
    ].join("\n");
    const { text, check } = sliceBrief(
      source,
      "s.md",
      read,
      (p) => `MAP ${p.join(",")}`,
    );
    assert.match(
      text,
      /^<!-- Generated by tools\/slice-briefs\.ts from briefs\/src\/s\.md/,
    );
    assert.match(
      text,
      /> From `cards\.md` § 1 › Steps 1; Honesty \(lines 7, 12–13\):/,
    );
    assert.match(
      text,
      /1\. Add the table\.\n\n\*\*Honesty:\*\* say what is missing\./,
    );
    assert.match(text, /MAP packages\/db\/src\/a\.ts/);
    assert.deepEqual(check, {
      tests: ["packages/db/src/a.test.ts"],
      owns: ["packages/db/src/", "tools/"],
      map: ["packages/db/src/a.ts"],
    });
  });
  it("refuses dropped and unknown directives, and empty lists", () => {
    assert.throws(
      () => sliceBrief("@copy cards.md § 1", "s.md", read),
      /unknown directive @copy/,
    );
    assert.throws(
      () => sliceBrief("@routes /a", "s.md", read),
      /unknown directive @routes/,
    );
    assert.throws(
      () => sliceBrief("@owns", "s.md", read),
      /@owns names no paths/,
    );
    assert.throws(
      () => sliceBrief("@map a.ts", "s.md", read),
      /needs a code map/,
    );
    assert.throws(
      () => sliceBrief("@include cards.md 1", "s.md", read),
      /cannot read directive/,
    );
    assert.throws(
      () => sliceBrief("@size big", "s.md", read),
      /@size large <reason>/,
    );
  });
  it("refuses a long brief unless it says @size large, and leaves the map out of the count", () => {
    const long = Array.from(
      { length: BRIEF_MAX_LINES + 1 },
      (_, i) => `line ${i}`,
    ).join("\n");
    assert.throws(() => sliceBrief(long, "s.md", read), /over 400/);
    assert.doesNotThrow(() =>
      sliceBrief(`@size large it is one job\n${long}`, "s.md", read),
    );
    const bigMap = () => Array.from({ length: 500 }, () => "m").join("\n");
    assert.doesNotThrow(() =>
      sliceBrief("@map a.ts\nshort", "s.md", read, bigMap),
    );
  });
});
