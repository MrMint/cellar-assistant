/**
 * Hard negatives for the retrieval eval (N05): real products chosen to sit
 * next to an entry in `catalog.ts` and be confused with it.
 *
 * The first baseline ran on the target entries alone and scored 94% hit@1 —
 * not because retrieval is good, but because a six-type catalog of 63 items
 * leaves a query five to eighteen candidates of its own type to choose from.
 * A production catalog has hundreds of Scotches and Pinot Noirs, so this adds
 * what makes the choice hard there:
 *
 *  - **the sibling**: Lagavulin 8 beside Lagavulin 16, Pliny the Younger
 *    beside the Elder, Dassai 39 between 45 and 23, Pavillon Rouge beside
 *    Château Margaux, Hendrick's Orbium, Tanqueray No. Ten, Don Julio 1942;
 *  - **the same house**: more Buffalo Trace, Antinori, Twinings and
 *    Stumptown, which the brand queries must now find and the menu lines must
 *    now *not* confuse;
 *  - **the same description**: other smoky Islay malts, Provence rosés,
 *    hazy IPAs, lambics and barrel-aged stouts, which semantic queries should
 *    find (they are added to those queries' `relevant` sets) and name queries
 *    should rank below the one named.
 *
 * Nothing here is the expected answer of a menu line; some are in a query's
 * `relevant` set where they genuinely answer it.
 */
import type { CatalogEntry } from "./catalog.ts";

const spirit = (
  key: string,
  name: string,
  spiritType: string,
  country: string,
  abv: number,
  brand: string,
  description: string,
): CatalogEntry => ({
  key: `spirit.${key}`,
  type: "SPIRIT",
  name,
  description,
  country,
  attributes: { spiritType, alcoholContentPercentage: abv },
  brands: [brand],
});

const wine = (
  key: string,
  name: string,
  year: number,
  style: string,
  variety: string,
  region: string,
  country: string,
  brand: string,
  description: string,
): CatalogEntry => ({
  key: `wine.${key}`,
  type: "WINE",
  name,
  description,
  country,
  attributes: { vintage: `${year}-01-01`, style, variety, region },
  brands: [brand],
});

const beer = (
  key: string,
  name: string,
  style: string,
  country: string,
  abv: number,
  brand: string,
  description: string,
): CatalogEntry => ({
  key: `beer.${key}`,
  type: "BEER",
  name,
  description,
  country,
  attributes: { style, alcoholContentPercentage: abv },
  brands: [brand],
});

const coffee = (
  key: string,
  name: string,
  country: string,
  roastLevel: string,
  process: string,
  description: string,
  brand?: string,
): CatalogEntry => ({
  key: `coffee.${key}`,
  type: "COFFEE",
  name,
  description,
  country,
  attributes: { roastLevel, process, species: "ARABICA" },
  ...(brand === undefined ? {} : { brands: [brand] }),
});

const sake = (
  key: string,
  name: string,
  category: string,
  sakeType: string,
  region: string,
  brand: string,
  description: string,
): CatalogEntry => ({
  key: `sake.${key}`,
  type: "SAKE",
  name,
  description,
  country: "JAPAN",
  attributes: { category, sakeType, region },
  brands: [brand],
});

const tea = (
  key: string,
  name: string,
  category: string,
  form: string,
  country: string,
  description: string,
  brand?: string,
): CatalogEntry => ({
  key: `tea.${key}`,
  type: "TEA",
  name,
  description,
  country,
  attributes: { category, form },
  ...(brand === undefined ? {} : { brands: [brand] }),
});

